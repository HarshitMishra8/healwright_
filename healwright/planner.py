"""Plain English -> test spec (via an LLM), and test spec -> plain Playwright code."""

from __future__ import annotations

from .llm import LLMProvider, extract_json
from .spec import Step, TestSpec

PLAN_SYSTEM = (
    "You turn a plain-English description of a web UI test into structured steps. "
    "Allowed actions: goto (value = URL or path), click, fill (value = text to type), "
    "expect_text (value = text that must appear), expect_visible. "
    "Each step needs an 'intent': a short human description of the element, e.g. "
    "'the username field' or 'the Log in button'. Do NOT write CSS selectors. "
    'Reply with JSON only: {"name": "<short test name>", "steps": [{"action": ..., "intent": ..., "value": ...}]}'
)


def plan(description: str, provider: LLMProvider, start_url: str | None = None) -> TestSpec:
    user = description if not start_url else f"Start URL: {start_url}\n\n{description}"
    data = extract_json(provider.complete(PLAN_SYSTEM, user))
    steps = [Step(**{k: v for k, v in s.items() if k in ("action", "intent", "value")}) for s in data["steps"]]
    if start_url and (not steps or steps[0].action != "goto"):
        steps.insert(0, Step(action="goto", intent="open the start page", value=start_url))
    return TestSpec(name=data.get("name", "generated test"), steps=steps)


def export_pytest(spec: TestSpec, base_url: str = "") -> str:
    """Generate a plain pytest-playwright test from a spec that has selectors.

    Lets users "graduate" a test to ordinary Playwright with no Healwright dependency.
    """
    fn = "test_" + "".join(ch if ch.isalnum() else "_" for ch in spec.name.lower()).strip("_")
    lines = [
        '"""Generated by healwright export. Edit freely."""',
        "from urllib.parse import urljoin",
        "",
        "from playwright.sync_api import Page, expect",
        "",
        f"BASE_URL = {(base_url or spec.base_url or '')!r}",
        "",
        "",
        f"def {fn}(page: Page):",
    ]
    for s in spec.steps:
        lines.append(f"    # {s.intent}")
        if s.action == "goto":
            lines.append(f"    page.goto(urljoin(BASE_URL, {s.value!r}))")
            continue
        if not s.selector:
            raise ValueError(f"Step {s.intent!r} has no selector yet: run with --update first")
        loc = f"page.locator({s.selector!r})"
        if s.action == "click":
            lines.append(f"    {loc}.click()")
        elif s.action == "fill":
            lines.append(f"    {loc}.fill({s.value!r})")
        elif s.action == "expect_text":
            lines.append(f"    expect({loc}).to_contain_text({s.value!r})")
        elif s.action == "expect_visible":
            lines.append(f"    expect({loc}).to_be_visible()")
    return "\n".join(lines) + "\n"
